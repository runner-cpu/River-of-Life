const fields = ['definition', 'fact', 'misconception'] as const;
const prompts = {
  definition: '根据展品卡，哪项最准确地描述',
  fact: '观察展品细节，哪项是关于它的可靠认识：',
  misconception: '面对常见误解，哪项解释符合展品证据：',
};

export const questions: Question[] = species.flatMap((entry, entryIndex) => fields.map((field, fieldIndex) => {
  const correct = (entryIndex + fieldIndex) % 4;
  const options: string[] = [...distractors[entry.id]!];
  options.splice(correct, 0, entry[field]);
  return {
    id: `${entry.id}-${field}`,
    speciesId: entry.id,
    chapter: entry.chapter,
    prompt: field === 'definition'
      ? `${prompts.definition}“${entry.name}”？`
      : `“${entry.name}”——${prompts[field]}`,
    options,
    correct,
    explanation: `展品卡${field === 'definition' ? '“生命档案”' : field === 'fact' ? '“值得留意”' : '“纠正误解”'}写道：${entry[field]}`,
    field,
  };
}));
